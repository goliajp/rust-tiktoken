//! Generator for `tables.rs`. The category of every code point is read from
//! the `regex` crate's `\p{..}` classes, so the tables pin exactly the
//! Unicode version the patterns were checked against.
//!
//! Regenerate after a `regex` upgrade with
//! `cargo test -p tiktoken --lib unicode::generate -- --ignored`.

use super::*;

pub(super) const MAX_CP: u32 = 0x10FFFF;

/// Every scalar value matched by `class`, as a membership vector over
/// `0..=MAX_CP`.
pub(super) fn members(class: &str) -> Vec<bool> {
    let all: String = (0..=MAX_CP).filter_map(char::from_u32).collect();
    let re = regex::Regex::new(&format!("{class}+")).unwrap();
    let mut out = vec![false; MAX_CP as usize + 1];
    for m in re.find_iter(&all) {
        for c in m.as_str().chars() {
            out[c as usize] = true;
        }
    }
    out
}

/// The category byte of every code point (surrogates get [`OTHER`]).
pub(super) fn categories() -> Vec<u8> {
    let groups: [(&str, u8); 10] = [
        (r"\p{Lu}", LU),
        (r"\p{Ll}", LL),
        (r"\p{Lt}", LT),
        (r"\p{Lm}", LM),
        (r"\p{Lo}", LO),
        (r"\p{M}", MARK),
        (r"\p{N}", NUM),
        (r"\p{P}", PUNCT),
        (r"\p{S}", SYM),
        (r"\p{Z}", SEP),
    ];
    let mut cats = vec![OTHER; MAX_CP as usize + 1];
    for (class, group) in groups {
        for (cp, is) in members(class).into_iter().enumerate() {
            if is {
                assert_eq!(cats[cp], OTHER, "U+{cp:04X} is in two groups");
                cats[cp] = group;
            }
        }
    }
    for (cp, is) in members(r"\p{Han}").into_iter().enumerate() {
        if is {
            cats[cp] |= HAN;
        }
    }
    for (cp, is) in members(r"\s").into_iter().enumerate() {
        if is {
            cats[cp] |= WS;
        }
    }
    for cp in *b"\r\n" {
        cats[cp as usize] = NL | WS;
    }
    cats
}

const SHIFT: u32 = 8;

pub(super) fn render(cats: &[u8]) -> String {
    let block_len = 1usize << SHIFT;
    let mut blocks: Vec<&[u8]> = Vec::new();
    let mut stage1 = Vec::new();
    for chunk in cats.chunks(block_len) {
        let idx = match blocks.iter().position(|b| *b == chunk) {
            Some(i) => i,
            None => {
                blocks.push(chunk);
                blocks.len() - 1
            }
        };
        stage1.push(idx);
    }
    assert!(
        blocks.len() <= 256,
        "{} blocks need a u16 stage 1",
        blocks.len()
    );

    let mut s = String::new();
    s.push_str("// CODEGEN: unicode tables\n");
    s.push_str("// generated by src/unicode/generate.rs from the regex crate's unicode data\n\n");
    s.push_str(&format!("pub(super) const SHIFT: u32 = {SHIFT};\n"));
    s.push_str(&format!(
        "pub(super) const LOW_MASK: usize = {};\n\n",
        block_len - 1
    ));
    push_array(&mut s, "ASCII", &cats[..128]);
    let stage1: Vec<u8> = stage1.iter().map(|&i| i as u8).collect();
    push_array(&mut s, "STAGE1", &stage1);
    let stage2: Vec<u8> = blocks.concat();
    push_array(&mut s, "STAGE2", &stage2);
    s.truncate(s.trim_end().len() + 1);
    s
}

fn push_array(s: &mut String, name: &str, data: &[u8]) {
    s.push_str(&format!(
        "#[rustfmt::skip]\npub(super) static {name}: [u8; {}] = [\n",
        data.len()
    ));
    for line in data.chunks(32) {
        let items: Vec<String> = line.iter().map(|v| v.to_string()).collect();
        s.push_str(&items.join(","));
        s.push_str(",\n");
    }
    s.push_str("];\n\n");
}

const TABLES_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/src/unicode/tables.rs");

#[test]
#[ignore = "rewrites src/unicode/tables.rs"]
fn regenerate() {
    std::fs::write(TABLES_PATH, render(&categories())).unwrap();
}

#[test]
fn tables_are_current() {
    let committed = std::fs::read_to_string(TABLES_PATH).unwrap();
    assert!(
        committed == render(&categories()),
        "tables.rs is stale: run the ignored `regenerate` test"
    );
}
